class TemplateConsistencyTests(unittest.TestCase):
    def test_the_manifest_lists_the_migration_and_the_new_version(self) -> None:
        text = lf(ROOT / ".template_sync/manifest.yaml")
        self.assertRegex(text, r"template_version: 0\.1\.(2[5-9]|[3-9][0-9])\b")
        self.assertIn("script: migrations/v0_1_24_to_v0_1_25.py", text)

    def test_chains_from_every_older_version_reach_0_1_25(self) -> None:
        sync = load(SYNC_PATH, "sync_for_0_1_25")
        manifest = sync.parse_manifest(ROOT / ".template_sync/manifest.yaml")
        for start in ("0.0.0", "0.1.9", "0.1.19", "0.1.20", "0.1.24"):
            chain = sync.resolve_migration_chain(manifest["migrations"], start, "0.1.25")
            self.assertEqual(chain[-1]["to"], "0.1.25", start)

    def test_the_design_note_is_linked(self) -> None:
        self.assertIn("(migration_0_1_25.md)", lf(ROOT / ".tools/docs/README.md"))
        self.assertTrue((ROOT / ".tools/docs/migration_0_1_25.md").is_file())

    def test_the_resources_are_the_live_files(self) -> None:
        for relative in (WORKFLOW, MIGRATION.PACKAGE_SCRIPT, SETUP, MANIFEST_IN):
            with self.subTest(file=str(relative)):
                self.assertEqual((MIGRATION.RESOURCE_ROOT / relative).read_bytes(), (ROOT / relative).read_bytes())

    def test_the_live_bump_version_is_the_0_1_24_file_migrated(self) -> None:
        self.assertNotEqual(bump_0_1_24(), lf(ROOT / BUMP))
        self.assertEqual(MIGRATION.apply_blocks(bump_0_1_24(), MIGRATION.BUMP_BLOCKS), lf(ROOT / BUMP))

    def test_the_setup_py_keeps_the_placeholders_the_form_and_the_scripts_fill_in(self) -> None:
        text = template_setup()
        for placeholder in ('name="PYTHON_PROJ_NAME"', 'version="VERSION_NUMBER"', 'python_requires=">=PYTHON_VERSION"'):
            self.assertEqual(text.count(placeholder.split('"')[1]), 1, placeholder)
            self.assertIn(placeholder, text)
        # bump_constructor.py takes the first name="..." of setup.py as the name of the package
        self.assertEqual(re.search(r'name\s*=\s*["\']([^"\']+)["\']', text).group(1), "PYTHON_PROJ_NAME")  # type: ignore[union-attr]
        # merge_requirements.py writes the Python series with this pattern
        merged = re.sub(r'python_requires\s*=\s*["\'][><=\.0-9 ]+(PYTHON\_VERSION)?["\']', 'python_requires=">=3.12"', text)
        self.assertIn('python_requires=">=3.12"', merged)
        # once initialised, the installer's placeholder check finds nothing in it
        check = load(ROOT / ".tools/python/check_placeholders.py", "check_placeholders_0_1_25")
        with tempfile.TemporaryDirectory() as tmp:
            (Path(tmp) / "setup.py").write_text(template_setup(VALUES), encoding="utf-8")
            self.assertEqual(check.leftover_placeholders(Path(tmp)), [])
            (Path(tmp) / "setup.py").write_text(template_setup({**VALUES, "name": "PYTHON_PROJ_NAME"}), encoding="utf-8")
            self.assertEqual(len(check.leftover_placeholders(Path(tmp))), 1)

    def test_the_workflow_is_off_by_default_and_uses_trusted_publishing(self) -> None:
        text = lf(ROOT / WORKFLOW)
        data = yaml.safe_load(text)
        self.assertEqual(data[True], {"release": {"types": ["published"]}})  # `on:` is True for PyYAML
        self.assertEqual(data["permissions"], {"contents": "read"})
        condition = "vars.PYPI_PUBLISH == 'true' || vars.PYPI_PUBLISH == 'testpypi'"
        build, publish = data["jobs"]["build"], data["jobs"]["publish"]
        self.assertEqual((build["if"], publish["if"]), (condition, condition))
        self.assertEqual(publish["needs"], "build")
        self.assertEqual(publish["environment"]["name"], "pypi")
        self.assertEqual(publish["permissions"], {"id-token": "write"})
        self.assertNotIn("permissions", build)
        self.assertNotIn("secrets.", text)
        self.assertNotIn("password", text)
        for job in (build, publish):
            for step in job["steps"]:
                if "uses" in step:
                    self.assertRegex(step["uses"], r"^[\w.-]+/[\w.-]+@[0-9a-f]{40}$", "pinned by SHA")
        upload = publish["steps"][-1]
        self.assertTrue(upload["uses"].startswith("pypa/gh-action-pypi-publish@"))
        self.assertIn("https://test.pypi.org/legacy/", upload["with"]["repository-url"])
        run = next(step for step in build["steps"] if step.get("id") == "build")
        self.assertEqual(run["env"]["TAG"], "${{ github.event.release.tag_name }}")
        self.assertIn('--version "${TAG#v}"', run["run"])
        self.assertIn("python .tools/python/pypi_package.py", run["run"])


class SetupPyTests(unittest.TestCase):
    """The template's setup.py, run with a stand-in for setuptools.setup: what it passes for an app."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)
        (self.root / "setup.py").write_text(template_setup(VALUES), encoding="utf-8")
        (self.root / "src/cell_analyzer").mkdir(parents=True)
        (self.root / "src/cell_analyzer/__init__.py").write_text("", encoding="utf-8")

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def arguments(self, blocked: tuple[str, ...] = ()) -> dict[str, Any]:
        seen: dict[str, Any] = {}
        modules: dict[str, Any] = {name: None for name in blocked}
        # setuptools runs setup.py in its folder (find_packages(where="src") is relative to it)
        with mock.patch("setuptools.setup", lambda **kwargs: seen.update(kwargs)), mock.patch.dict(sys.modules, modules), chdir(self.root):
            runpy.run_path(str(self.root / "setup.py"), run_name="__main__")
        return seen

    def test_without_requirements_or_readme_it_still_installs(self) -> None:
        """The installer: no README.md next to setup.py, and an app without requirements."""
        args = self.arguments()
        self.assertEqual((args["name"], args["version"], args["python_requires"]), ("cell_analyzer", "0.0.1", ">=3.12"))
        self.assertEqual((args["install_requires"], args["long_description"]), ([], ""))
        self.assertEqual(args["packages"], ["cell_analyzer"])

    def test_the_requirements_and_the_readme_are_read(self) -> None:
        (self.root / "requirements.txt").write_text(REQUIREMENTS, encoding="utf-8")
        (self.root / "README.md").write_text("# Cell Analyzer\n", encoding="utf-8")
        with mock.patch.dict("os.environ", {"GITHUB_REPOSITORY": "me/cell-analyzer"}):
            args = self.arguments()
        self.assertEqual(args["install_requires"], ["numpy==2.0.2", "scikit-image>=0.26", 'torch==2.1.0+cu118 ; sys_platform == "linux"'])
        self.assertEqual(args["long_description"], "# Cell Analyzer\n")
        self.assertEqual(args["long_description_content_type"], "text/markdown")
        self.assertEqual(args["project_urls"], {"Source": "https://github.com/me/cell-analyzer"})

    def test_without_packaging_the_same_lines_are_kept(self) -> None:
        (self.root / "requirements.txt").write_text(REQUIREMENTS, encoding="utf-8")
        with_packaging = self.arguments()["install_requires"]
        self.assertEqual(self.arguments(blocked=("packaging", "packaging.requirements"))["install_requires"], with_packaging)


class PrepareTests(unittest.TestCase):
    """The checks of pypi_package.py before anything is built."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)
        (self.root / "setup.py").write_text(template_setup(VALUES), encoding="utf-8")
        (self.root / "src/cell_analyzer").mkdir(parents=True)
        (self.root / "src/cell_analyzer/__init__.py").write_text("", encoding="utf-8")
        (self.root / ".github/workflows").mkdir(parents=True)
        shutil.copy(ROOT / WORKFLOW, self.root / WORKFLOW)

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def prepare(self, version: str = "1.2.3", answer: bool | None = False) -> str:
        with mock.patch.object(PACKAGE, "version_on_index", return_value=answer), redirect_stdout(StringIO()):
            return str(PACKAGE.prepare(self.root, version, "pypi"))

    def manifest(self, pip: str) -> None:
        (self.root / "labconstrictor-app.yaml").write_text(yaml.safe_dump({"name": "Cell Analyzer", "distribution": {"pip": pip}}), encoding="utf-8")

    def test_the_release_version_is_written_into_setup_py(self) -> None:
        self.assertEqual(self.prepare("1.2.3"), "cell_analyzer")
        self.assertIn('version="1.2.3",', lf(self.root / "setup.py"))
        self.assertEqual(lf(self.root / "setup.py"), template_setup({**VALUES, "version": "1.2.3"}))

    def test_crlf_is_kept(self) -> None:
        (self.root / "setup.py").write_bytes(template_setup(VALUES).replace("\n", "\r\n").encode("utf-8"))
        self.prepare("1.2.3")
        data = (self.root / "setup.py").read_bytes()
        self.assertNotIn(b"\n", data.replace(b"\r\n", b""))
        self.assertIn(b'version="1.2.3"', data)

    def test_no_package_in_src(self) -> None:
        shutil.rmtree(self.root / "src")
        (self.root / "src").mkdir()
        (self.root / "src/.gitkeep").write_text("", encoding="utf-8")
        with self.assertRaisesRegex(PACKAGE.PackageError, "no Python package in src/"):
            self.prepare()

    def test_a_version_that_is_not_x_y_z(self) -> None:
        with self.assertRaisesRegex(PACKAGE.PackageError, "is not X.Y.Z"):
            self.prepare("1.2.3rc1")

    def test_a_version_already_on_the_index_stops_before_the_build(self) -> None:
        with self.assertRaisesRegex(PACKAGE.PackageError, r"PyPI already has cell_analyzer 1\.2\.3.*/project/cell-analyzer/1\.2\.3/"):
            self.prepare("1.2.3", answer=True)
        self.assertIn('version="0.0.1"', lf(self.root / "setup.py"), "nothing was written")

    def test_an_index_that_cannot_be_asked_is_a_warning(self) -> None:
        buffer = StringIO()
        with mock.patch.object(PACKAGE, "version_on_index", return_value=None), redirect_stdout(buffer):
            PACKAGE.prepare(self.root, "1.2.3", "testpypi")
        self.assertIn("WARNING: TestPyPI could not be asked", buffer.getvalue())

    def test_another_publishing_workflow_stops_it(self) -> None:
        """NucleiSky publishes with its own workflow: the two would upload the same release."""
        (self.root / ".github/workflows/publish_to_pypi.yml").write_text("steps:\n  - uses: pypa/gh-action-pypi-publish@abc\n", encoding="utf-8")
        with self.assertRaisesRegex(PACKAGE.PackageError, r"\.github/workflows/publish_to_pypi\.yml also publishes to PyPI"):
            self.prepare()

    def test_distribution_pip_must_name_the_same_package(self) -> None:
        self.manifest("Cell-Analyzer")
        self.assertEqual(self.prepare(), "cell_analyzer", "the same name for PyPI")
        self.manifest("vlab4mic")
        with self.assertRaisesRegex(PACKAGE.PackageError, "distribution.pip of labconstrictor-app.yaml is vlab4mic, but setup.py names the package cell_analyzer"):
            self.prepare()

    def test_a_placeholder_left_in_setup_py(self) -> None:
        (self.root / "setup.py").write_text(template_setup({**VALUES, "python": "PYTHON_VERSION"}), encoding="utf-8")
        with self.assertRaisesRegex(PACKAGE.PackageError, "still has the template placeholder PYTHON_VERSION"):
            self.prepare()

    def test_pyproject_must_give_the_release_version(self) -> None:
        (self.root / "pyproject.toml").write_text('[project]\nname = "nucleisky"\nversion = "0.0.1"\n', encoding="utf-8")
        with self.assertRaisesRegex(PACKAGE.PackageError, 'set `version = "1.2.3"` in pyproject.toml'):
            self.prepare()
        (self.root / "pyproject.toml").write_text('[project]\nname = "nucleisky"\nversion = "1.2.3"\n', encoding="utf-8")
        self.assertEqual(self.prepare(), "nucleisky")

    def test_the_index_is_asked_with_the_normalised_name(self) -> None:
        asked: list[str] = []

        def opener(url: str, timeout: int) -> Any:
            asked.append(url)
            raise urllib.error.HTTPError(url, 404, "Not Found", {}, None)  # type: ignore[arg-type]

        self.assertFalse(PACKAGE.version_on_index("testpypi", "Cell_Analyzer", "1.2.3", opener))
        self.assertEqual(asked, ["https://test.pypi.org/pypi/cell-analyzer/1.2.3/json"])
        self.assertIsNone(PACKAGE.version_on_index("pypi", "x", "1.2.3", mock.Mock(side_effect=urllib.error.URLError("offline"))))
        answer = mock.MagicMock()
        answer.__enter__.return_value.status = 200
        self.assertTrue(PACKAGE.version_on_index("pypi", "x", "1.2.3", mock.Mock(return_value=answer)))


def _fake_dists(folder: Path, name: str, version: str, requires: list[str], sdist_requires: list[str] | None = None) -> None:
    """A wheel and a source distribution with only their metadata."""
    def metadata(requirements: list[str]) -> bytes:
        lines = ["Metadata-Version: 2.4", f"Name: {name}", f"Version: {version}", *(f"Requires-Dist: {r}" for r in requirements)]
        return ("\n".join(lines) + "\n\n").encode("utf-8")

    with zipfile.ZipFile(folder / f"{name}-{version}-py3-none-any.whl", "w") as wheel:
        wheel.writestr(f"{name}-{version}.dist-info/METADATA", metadata(requires))
    with tarfile.open(folder / f"{name}-{version}.tar.gz", "w:gz") as sdist:
        data = metadata(requires if sdist_requires is None else sdist_requires)
        info = tarfile.TarInfo(f"{name}-{version}/PKG-INFO")
        info.size = len(data)
        sdist.addfile(info, io.BytesIO(data))


class CheckTests(unittest.TestCase):
    """The checks of pypi_package.py on the built files."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.dist = Path(self._tmp.name)

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def test_good_files(self) -> None:
        _fake_dists(self.dist, "cell_analyzer", "1.2.3", ["numpy==2.0.2"])
        self.assertEqual(PACKAGE.check(self.dist, "cell-analyzer", "1.2.3"), ["cell_analyzer-1.2.3.tar.gz", "cell_analyzer-1.2.3-py3-none-any.whl"])

    def test_another_version(self) -> None:
        _fake_dists(self.dist, "cell_analyzer", "0.0.1", [])
        with self.assertRaisesRegex(PACKAGE.PackageError, "has the version 0.0.1, not the release version 1.2.3"):
            PACKAGE.check(self.dist, "cell_analyzer", "1.2.3")

    def test_a_url_dependency_is_refused_as_pypi_would(self) -> None:
        """CellPatcher's setup.py needs morphobricks-preprocessing from GitHub."""
        _fake_dists(self.dist, "cellpatcher", "1.2.3", ["morphobricks-preprocessing @ git+https://github.com/CellMigrationLab/morphobricks-preprocessing@v0.5.1"])
        with self.assertRaisesRegex(PACKAGE.PackageError, "PyPI refuses a package whose dependency is a URL: morphobricks-preprocessing"):
            PACKAGE.check(self.dist, "cellpatcher", "1.2.3")

    def test_a_wheel_without_the_dependencies_of_the_source_distribution(self) -> None:
        _fake_dists(self.dist, "cell_analyzer", "1.2.3", [], sdist_requires=["numpy==2.0.2"])
        with self.assertRaisesRegex(PACKAGE.PackageError, "include requirements.txt"):
            PACKAGE.check(self.dist, "cell_analyzer", "1.2.3")

    def test_missing_files(self) -> None:
        with self.assertRaisesRegex(PACKAGE.PackageError, "found: nothing"):
            PACKAGE.check(self.dist, "cell_analyzer", "1.2.3")


@unittest.skipUnless(HAS_BUILD, "needs the build and setuptools packages (pip install build setuptools)")
class BuildTests(unittest.TestCase):
    """An initialised app built as the build job of publish_pypi.yml builds it (without network: --no-isolation --offline)."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name) / "app"
        (self.root / ".tools/python").mkdir(parents=True)
        (self.root / "src/cell_analyzer/tools").mkdir(parents=True)
        shutil.copy(PACKAGE_PATH, self.root / ".tools/python/pypi_package.py")
        for name in ("MANIFEST.in", "LICENSE"):
            shutil.copy(ROOT / name, self.root / name)
        (self.root / "setup.py").write_text(template_setup(VALUES), encoding="utf-8")
        (self.root / "requirements.txt").write_text(REQUIREMENTS, encoding="utf-8")
        (self.root / "README.md").write_text("# Cell Analyzer\n\nCounts cells.\n", encoding="utf-8")
        (self.root / "src/cell_analyzer/__init__.py").write_text("def count():\n    return 1\n", encoding="utf-8")
        (self.root / "src/cell_analyzer/tools/__init__.py").write_text("", encoding="utf-8")
        (self.root / "labconstrictor-app.yaml").write_text("schema: 1\nname: Cell Analyzer\ndistribution:\n  installer: true\n  pip: cell-analyzer\n", encoding="utf-8")

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def run_script(self, *extra: str) -> tuple[int, str, str]:
        command = [sys.executable, str(self.root / ".tools/python/pypi_package.py"), "--version", "1.2.3", "--no-isolation", "--offline", *extra]
        result = subprocess.run(command, capture_output=True, text=True, env={**os.environ, "GITHUB_REPOSITORY": "me/cell-analyzer"})
        return result.returncode, result.stdout, result.stderr

    def test_the_source_distribution_and_the_wheel(self) -> None:
        output = self.root / "github_output"
        code, stdout, stderr = self.run_script("--github-output", str(output))
        self.assertEqual(code, 0, stdout + stderr)
        for line in ("-r requirements_gpu.txt", "--extra-index-url https://download.pytorch.org/whl/cu118", "./wheels/local.whl", "mytool @ git+"):
            self.assertIn(f"WARNING: the line `{line}", stdout)
        self.assertIn("Built cell_analyzer 1.2.3 for PyPI", stdout)
        self.assertEqual(
            output.read_text(encoding="utf-8"), "name=cell_analyzer\nversion=1.2.3\nurl=https://pypi.org/project/cell-analyzer/1.2.3/\n"
        )
        dist = self.root / "dist"
        wheel, sdist, files = PACKAGE.read_metadata(dist)
        self.assertEqual([path.name for path in files], ["cell_analyzer-1.2.3.tar.gz", "cell_analyzer-1.2.3-py3-none-any.whl"])
        self.assertEqual((wheel["Name"], wheel["Version"], wheel["Requires-Python"]), ("cell_analyzer", "1.2.3", ">=3.12"))
        self.assertEqual(sdist["Version"], "1.2.3")
        self.assertEqual(wheel.get_all("Requires-Dist"), DEPENDENCIES)
        self.assertEqual(wheel["Description-Content-Type"], "text/markdown")
        self.assertEqual(wheel.get_all("Project-URL"), ["Source, https://github.com/me/cell-analyzer"])
        with zipfile.ZipFile(files[1]) as archive:
            names = archive.namelist()
            body = archive.read("cell_analyzer-1.2.3.dist-info/METADATA").decode("utf-8")
        self.assertIn("cell_analyzer/__init__.py", names)
        self.assertIn("cell_analyzer/tools/__init__.py", names)
        self.assertTrue(body.replace("\r\n", "\n").rstrip().endswith("# Cell Analyzer\n\nCounts cells."), "README.md is the description")
        with tarfile.open(files[0]) as archive:
            members = {member.name.split("/", 1)[1] for member in archive.getmembers() if "/" in member.name}
        self.assertLessEqual({"setup.py", "requirements.txt", "README.md", "LICENSE", "MANIFEST.in", "src/cell_analyzer/__init__.py"}, members)
        self.assertNotIn(".tools/python/pypi_package.py", members, "only the package, not the app")

    def test_a_dist_folder_left_from_before_stops_it(self) -> None:
        (self.root / "dist").mkdir()
        (self.root / "dist/cell_analyzer-1.2.2.tar.gz").write_bytes(b"")
        code, _, stderr = self.run_script()
        self.assertEqual(code, 1)
        self.assertIn("is not empty", stderr)
        self.assertIn("::error title=The package cannot be published::", stderr)


